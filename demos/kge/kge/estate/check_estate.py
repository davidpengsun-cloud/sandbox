"""The estate is additive: the tables an earlier estate had hold the same rows, and the question sets are the baseline's.

    python3 -m kge.estate.check_estate [--profile <id>] --snapshot clients/<client>/baselines/estate-<base>.json \
        --baseline clients/<client>/baselines/issue-38.json
    make check-estate

A change to the generator may add tables, columns and rows of its own, but
must not move a row the estate already had: one extra draw from a stream the
existing units use would regenerate every figure the golden and held-out sets
were computed from. So the snapshot freezes, per table of the earlier estate
(unit.table), its columns, its row count and a checksum of its rows: the
sha256 of each row's values, as JSON, the rows sorted, written in base32 so
no committed file carries a hex digest. The check computes the same over the
same columns of the build's warehouses: a column appended since is left out,
and a column gone, a row added or a value changed is a moved table. A table
renamed since, Wealth's kept tables under the physical names in SAGE's style
they took (kge/estate/names.py), is read under its new table and column names,
its rows as they were. It also
holds the question sets to the A/B baseline's files: build/heldout.json's
sha256 must be the baseline's, and so must golden v1's, which golden v2's file
names in its changes_from (kge/estate/golden.py), so no expected figure moved.

What the build has beyond the snapshot, tables and columns, is listed apart,
as the additions they are.

The snapshot is taken once, with --freeze, on an estate generated by the
commit it names, which never overwrites one, and is never edited.

Exit 0: every table and both sets unchanged. 1: something moved. 2: it cannot
check: no snapshot, no warehouses, or no set files.

Reads the warehouses (read only) and the set files of the profile's estate
(kge/pipeline/profile.py: --profile, else PROFILE, else the registry's default;
--build names another); never the graph.
"""
from __future__ import annotations

import argparse
import base64
import datetime as dt
import decimal
import hashlib
import json
import sys
from pathlib import Path

from kge.pipeline.settings import ROOT
from kge.ports import EstateWarehouses

DEMO = ROOT


def value(v):
    """One value as the checksum reads it: a decimal keeps its scale, a date its ISO form."""
    if isinstance(v, decimal.Decimal):
        return str(v)
    if isinstance(v, (dt.date, dt.datetime)):
        return v.isoformat()
    if isinstance(v, float):
        return repr(v)
    return v


def table_checksum(con, table: str, columns: list[str]) -> tuple[int, str]:
    """(rows, checksum) of a table over the named columns: the sha256 of its rows, each its values as JSON, sorted, in base32."""
    rows = con.execute(f"SELECT {', '.join(columns)} FROM {table}").fetchall()
    lines = sorted(json.dumps([value(v) for v in r], ensure_ascii=False) for r in rows)
    digest = hashlib.sha256(("\n".join(lines) + "\n").encode()).digest()
    return len(rows), base64.b32encode(digest).decode().rstrip("=").lower()


def catalogue(estate: EstateWarehouses, unit: str) -> dict[str, list[str]]:
    """A warehouse's tables, each with its columns in position order."""
    con = estate.open(unit)
    try:
        return {t: [c["name"] for c in con.describe(t)["columns"]] for t in con.tables()}
    finally:
        con.close()


def checksums(warehouses, tables: dict[str, list[str]] | None = None) -> dict[str, dict]:
    """"unit.table" -> {columns, rows, checksum}: every table of every established warehouse (warehouses: the estate's,
    or the folder of DuckDB files), or only the tables named, each over the columns named for it (a table or column
    missing is left out: the caller says so)."""
    estate = _estate(warehouses)
    out = {}
    for unit in estate.established():
        have = catalogue(estate, unit)
        want = {t: cols for t, cols in have.items()} if tables is None else \
            {k.split(".", 1)[1]: cols for k, cols in tables.items() if k.split(".", 1)[0] == unit}
        con = estate.open(unit)
        try:
            for t, cols in sorted(want.items()):
                if t not in have or any(c not in have[t] for c in cols):
                    continue
                n, checksum = table_checksum(con, t, cols)
                out[f"{unit}.{t}"] = {"columns": list(cols), "rows": n, "checksum": checksum}
        finally:
            con.close()
    return out


def _estate(warehouses) -> EstateWarehouses:
    """The estate's warehouses, through the factory: given, or the folder's (the profile's client)."""
    if hasattr(warehouses, "established"):
        return warehouses
    from kge.estate.golden import warehouses as estate_at
    return estate_at(Path(warehouses).parent)


def renamed(tables: dict[str, dict], renames: dict[str, tuple[str, dict[str, str]]]) -> dict[str, dict]:
    """The snapshot's tables under the names the build gives them: a table renamed since (renames: unit.table -> (its
    physical name, {column: physical column})) under its physical names, its columns in the same order, so its rows and
    their checksum are read as they were."""
    out = {}
    for key, t in tables.items():
        unit, name = key.split(".", 1)
        if key in renames:
            physical, columns = renames[key]
            out[f"{unit}.{physical}"] = {**t, "columns": [columns.get(c, c) for c in t["columns"]]}
        else:
            out[key] = t
    return out


def physical_names() -> dict[str, tuple[str, dict[str, str]]]:
    """Wealth's kept tables, renamed to physical names in SAGE's style since the snapshot (kge/estate/names.py)."""
    from kge.estate.names import MERIDIAN
    return {f"wealth.{business}": spec for business, spec in MERIDIAN.items()}


def compare(snapshot: dict, build, client: str | None = None) -> tuple[list[str], dict]:
    """(what moved, one line per table; what the build adds: {tables: [...], columns: [...]}). build: the estate's folder,
    or its warehouses (the port's). A table renamed since is read under its new names (renamed)."""
    then = renamed(snapshot["tables"], physical_names())
    if hasattr(build, "established"):
        estate = build
    else:
        from kge.estate.golden import warehouses as estate_at
        estate = estate_at(Path(build), client)
    now = checksums(estate, {k: t["columns"] for k, t in then.items()})
    have = {f"{u}.{t}": cols for u in estate.established() for t, cols in catalogue(estate, u).items()}
    moved = []
    for key, t in sorted(then.items()):
        if key not in have:
            moved.append(f"{key}: gone")
        elif key not in now:
            gone = [c for c in t["columns"] if c not in have[key]]
            moved.append(f"{key}: column{'s' if len(gone) > 1 else ''} {', '.join(gone)} gone")
        elif now[key]["rows"] != t["rows"]:
            moved.append(f"{key}: {now[key]['rows']:,} rows, where it had {t['rows']:,}")
        elif now[key]["checksum"] != t["checksum"]:
            moved.append(f"{key}: the same {t['rows']:,} rows, but a value moved")
    added = {"tables": sorted(k for k in have if k not in then),
             "columns": [f"{k}.{c}" for k in sorted(then) if k in have for c in have[k] if c not in then[k]["columns"]]}
    return moved, added


def sets_moved(build: Path, baseline: dict) -> tuple[list[str], list[str]]:
    """(what moved, what held) of the question sets beside the baseline's files: heldout.json, and golden v1 as golden
    v2's changes_from names it."""
    moved, held = [], []
    sets = baseline.get("sets", {})
    heldout = Path(build) / "heldout.json"
    want = sets.get("heldout", {}).get("sha256")
    if hashlib.sha256(heldout.read_bytes()).hexdigest() == want:
        held.append("heldout.json is the baseline's file")
    else:
        moved.append("heldout.json: its sha256 is not the baseline's: a held-out figure moved")
    golden = json.loads((Path(build) / "golden.json").read_text())
    named = golden.get("changes_from", {}).get("sha256") if isinstance(golden, dict) else None
    v1 = sets.get("golden", {})
    if v1.get("version") == "v1" and named == v1.get("sha256"):
        held.append("golden v1, which golden v2 changes from, is the baseline's file")
    elif v1.get("version") == "v1":
        moved.append("golden.json: the v1 its changes_from names is not the baseline's file: a golden figure moved")
    return moved, held


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--profile", help="whose estate (default: PROFILE, else the registry's default)")
    ap.add_argument("--build", help="the estate to check, instead of the profile's")
    ap.add_argument("--snapshot", required=True, help="the frozen snapshot, clients/<client>/baselines/estate-<base>.json")
    ap.add_argument("--baseline", help="the A/B baseline whose set files the build's must be (#38's, "
                                       "clients/<client>/baselines/issue-38.json)")
    ap.add_argument("--freeze", metavar="TAKEN_ON", help="take the snapshot instead, from the build's warehouses, naming the commit "
                                                         "that generated them; never overwrites one")
    args = ap.parse_args(argv)
    from kge.pipeline.profile import ProfileError, resolve
    from kge.estate.golden import warehouses as estate_at
    try:
        prof = resolve(args.profile)
    except ProfileError as exc:
        print(f"check-estate: {exc}", file=sys.stderr)
        return 2
    build = Path(args.build) if args.build else prof.estate()
    estate = estate_at(build, prof.client)
    path = Path(args.snapshot)
    if not estate.established():
        print(f"check-estate: no warehouses in {build / 'warehouses'}: make estate first", file=sys.stderr)
        return 2
    if args.freeze:
        if path.exists():
            print(f"check-estate: {path} exists, and a snapshot is frozen: take a new one under its own name", file=sys.stderr)
            return 2
        tables = checksums(estate)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps({
            "about": "The estate's tables (kge/estate/check_estate.py): per unit.table, its columns, its row count and a checksum of its "
                     "rows, the sha256 of each row's values as JSON, the rows sorted, in base32. No row is held. Frozen: taken once, "
                     "never edited.",
            "taken_on": args.freeze, "tables": tables}, indent=1, sort_keys=True) + "\n")
        print(f"check-estate: froze {len(tables)} tables in {path}, taken on {args.freeze}")
        return 0
    if not path.is_file():
        print(f"check-estate: no snapshot {path}", file=sys.stderr)
        return 2
    baseline = None
    if args.baseline:
        missing = [n for n in ("heldout.json", "golden.json") if not (build / n).is_file()]
        if missing:
            print(f"check-estate: no {' or '.join(missing)} in {build}: make estate first", file=sys.stderr)
            return 2
        baseline = json.loads(Path(args.baseline).read_text())
    snap = json.loads(path.read_text())
    moved, added = compare(snap, estate)
    ncols = sum(len(t["columns"]) for t in snap["tables"].values())
    nrows = sum(t["rows"] for t in snap["tables"].values())
    print(f"check-estate: the {len(snap['tables'])} tables of {snap.get('taken_on')} ({path}), over their {ncols} columns, "
          f"{nrows:,} rows")
    held = []
    if baseline is not None:
        set_moves, held = sets_moved(build, baseline)
        moved += set_moves
    if added["tables"] or added["columns"]:
        print(f"  added since: {len(added['tables'])} tables ({', '.join(added['tables'])})"
              + (f"; {len(added['columns'])} columns on tables it had ({', '.join(added['columns'])})" if added["columns"] else ""))
    for line in held:
        print(f"  {line} ({args.baseline})")
    if moved:
        print(f"\nFAILED: {len(moved)} moved:")
        for line in moved:
            print("  " + line)
        print("\nThe estate is added to, never changed: new data comes from a seeded stream of its own.")
        return 1
    print(f"\npassed: every one of the {len(snap['tables'])} tables holds the rows it held" + (", and the sets are the baseline's" if held else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
